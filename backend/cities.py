def search_cities(q: str, limit: int = 12):
    q = (q or "").strip().lower()
    rows = [{"name": n, "region": r, "lat": la, "lon": lo, "tz": tz} for n, r, la, lo, tz in CITIES]
    if not q:
        return rows[:limit]
    starts = [c for c in rows if c["name"].lower().startswith(q)]
    contains = [c for c in rows if q in (c["name"] + " " + c["region"]).lower() and c not in starts]
    return (starts + contains)[:limit]
